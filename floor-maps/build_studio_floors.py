"""PP 4 (Oct 25 2026): Floors 4 and 5 rebuilt as Recording A and Recording B -- three studios each.

Rewrites ONLY the records for floors 4 and 5 in Hallways/DefaultMazes.json, keeping each floor's
own floor-level choices (corridor wall/floor/ceiling textures, camera-roll pictures, a user-imported
floor texture) and writing the file back in exactly the format Xcode's editor export uses (so the
other fourteen floors are byte-for-byte unchanged). The studio geometry here must match
Hallways/StudioRegistry.swift (StudioTests checks that it does).

    python3 floor-maps/build_studio_floors.py            (from the project folder)
"""
import json, os, sys
sys.path.insert(0, os.path.expanduser('~/hwtools'))
from applejson import dump

PATH = 'Hallways/DefaultMazes.json'

def g(r, c): return {'col': c, 'row': r}
def block(rows, cols): return [(r, c) for r in rows for c in cols]

# Each studio: room cells (rows x cols), the vestibule (the short way in from the corridor), the
# door's wall (from the vestibule into the room), and its look.
STUDIOS = {
    4: [
        dict(letter='A', rows=range(6, 9), cols=range(8, 12), vestibule=(9, 9), door='north',
             wall='Texturelabs_Wood_145S', floor='wood-walnut',
             ceiling='subtle-woven-white-texture-patternpictures-180126-300x300'),            # warm amber, wood
        dict(letter='B', rows=range(12, 15), cols=range(11, 15), vestibule=(11, 12), door='south',
             wall='Taupe-Wood-Planks-Seamless-Texture-171229-300x300', floor='_rubber_tiles',
             ceiling='subtle-woven-white-texture-patternpictures-180126-300x300'),            # cool, modern slats
        dict(letter='C', rows=range(9, 12), cols=range(17, 20), vestibule=(10, 16), door='east',
             wall='Chesterfield-leather-sofa-texture-seamless-repeating-patternpictures-5926-300x300',
             floor='dark-wood-strips', ceiling='subtle-woven-white-texture-patternpictures-180126-300x300'),  # deep red club
    ],
    5: [
        dict(letter='D', rows=range(12, 15), cols=range(7, 11), vestibule=(11, 9), door='south',
             wall='darkmoon_art-pattern-5649403_1920', floor='pexels-tiles-1846980_1920',
             ceiling='subtle-woven-white-texture-patternpictures-180126-300x300'),            # green and cream, vintage
        dict(letter='E', rows=range(6, 9), cols=range(11, 15), vestibule=(9, 12), door='north',
             wall='Black-Circles-Pattern-171119-300x300', floor='_gravel_concrete_03',
             ceiling='Perfectly-epeating-gold-jungle-botanical-tile-pattern-pictures-300x300'),  # charcoal and gold
        dict(letter='F', rows=range(9, 12), cols=range(16, 20), vestibule=(10, 15), door='east',
             wall='Shiney-metal-corrugated-sheets-texture-patternpictures-2118-300x300', floor='floor-carpet1',
             ceiling='macey11-arch-9796796_1920'),                                             # silver, experimental
    ],
}
CORRIDOR = {4: range(7, 16), 5: range(7, 15)}      # row 10, from the elevator (10,6) east
ELEVATOR = (10, 6)

DELTA = {'north': (-1, 0), 'south': (1, 0), 'east': (0, 1), 'west': (0, -1)}

def build(old, floor):
    rec = dict(old)
    studios = STUDIOS[floor]
    corridor = [(10, c) for c in CORRIDOR[floor]]
    cells = [ELEVATOR] + corridor
    for s in studios:
        cells.append(s['vestibule'])
        cells += block(s['rows'], s['cols'])
    assert len(set(cells)) == len(cells), 'overlap'
    rec['cells'] = [g(*c) for c in cells]
    # Doors: double glass (the existing wide door, 1.9 m), lettered, from each vestibule into its studio.
    rec['roomEntranceDoors'] = [{'coord': g(*s['vestibule']), 'direction': s['door'], 'style': 'doubleGlass',
                                 'label': 'STUDIO ' + s['letter']} for s in studios]
    # Each studio's look (and its vestibule's, so the entrance reads from the corridor).
    surf = []
    for s in studios:
        for c in [s['vestibule']] + block(s['rows'], s['cols']):
            surf.append({'coord': g(*c), 'wallTexture': s['wall'], 'floorTexture': s['floor'], 'ceilingTexture': s['ceiling']})
    rec['cellSurfaces'] = surf
    # Light: the corridor every other cell; each studio a fixture in every cell of its middle row and
    # its two back corners' row (bright, even light for a gathering).
    fl, lb = [], []
    for c in corridor[::2]:
        fl.append({'coord': g(*c), 'isAutoGenerated': False, 'orientation': 'eastWest'}); lb.append({'coord': g(*c), 'kind': 'fluorescent', 'level': 5})
    for s in studios:
        rows = list(s['rows']); cols = list(s['cols'])
        horiz = s['door'] in ('north', 'south')
        for r in rows[1:2] if horiz else rows:
            for c in (cols if horiz else cols[1:2] + cols[-1:]):
                fl.append({'coord': g(r, c), 'isAutoGenerated': False, 'orientation': 'eastWest' if horiz else 'northSouth'})
                lb.append({'coord': g(r, c), 'kind': 'fluorescent', 'level': 6})
    rec['fluorescentLights'] = fl
    rec['lightBrightness'] = lb
    rec['ceilingVisibleFixture'] = []
    rec['pictureLights'] = []
    rec['wallLights'] = []
    rec['spotlights'] = [g(10, 7)]
    # The corridor: the floor's map by the elevator, an EXIT sign back to it, a clock, two pictures.
    rec['floorMaps'] = [{'coord': g(10, 7), 'direction': 'north'}]
    rec['exitSigns'] = [{'coord': g(10, 9 if floor == 4 else 8), 'direction': 'east'}]
    rec['clocks'] = [{'coord': g(10, 14 if floor == 4 else 11), 'direction': 'north' if floor == 4 else 'south'}]
    rec['pictures'] = ([{'coord': g(10, 11), 'direction': 'north', 'size': 'poster'},
                        {'coord': g(10, 8), 'direction': 'south', 'size': 'poster'}] if floor == 4 else
                       [{'coord': g(10, 10), 'direction': 'north', 'size': 'poster'},
                        {'coord': g(10, 13), 'direction': 'south', 'size': 'poster'}])
    rec['pictureImageSelections'] = []
    # Everything the old layouts placed by cell, gone with them (none of it fits the new rooms).
    for k in ('mirrors', 'extinguishers', 'fires', 'objects', 'destinations', 'missionSigns', 'roomDoors', 'itemRooms',
              'bathroomDoors', 'windowRooms', 'tables', 'desks', 'waterCoolers', 'officeChairs', 'floorLamps', 'aquariums',
              'filingCabinets', 'photoBooths', 'ticTacToeTerminals', 'shellGameStations', 'rockPaperScissorsTerminals',
              'higherLowerTerminals', 'fiveCardDrawTerminals', 'simonTerminals', 'hangmanTerminals', 'connectFourTerminals',
              'checkersTerminals', 'woidleTerminals', 'floorGlowSequences'):
        if k in rec: rec[k] = []
    # The user's own decorations that still fit -- on a corridor cell, on a face that is still a wall --
    # are kept (and win over the defaults above on the same face).
    keep_cells = set([ELEVATOR] + corridor)
    def is_wall(x):
        c = (x['coord']['row'], x['coord']['col'])
        if c not in keep_cells: return False
        if 'direction' not in x: return True
        dr, dc = DELTA[x['direction']]
        return (c[0] + dr, c[1] + dc) not in cells
    face = lambda x: (x['coord']['row'], x['coord']['col'], x.get('direction'))
    kept = {}
    for k in ('pictures', 'extinguishers', 'clocks', 'floorMaps', 'exitSigns', 'mirrors'):
        mine = rec.get(k, [])
        theirs = [x for x in old.get(k, []) if is_wall(x)]
        faces = {face(x) for x in theirs}
        rec[k] = theirs + [x for x in mine if face(x) not in faces]
        kept[k] = len(theirs)
    sel = [x for x in old.get('pictureImageSelections', []) if face(x) in {face(p) for p in rec['pictures']}]
    rec['pictureImageSelections'] = sel
    kept['pictureImageSelections'] = len(sel)
    print('floor', floor, 'kept from the old layout:', kept)
    rec['missionHeading'] = 'Recording A' if floor == 4 else 'Recording B'
    rec['missionBody'] = ''
    rec['nextMazeID'] = floor + 1
    return rec

src = open(PATH).read()
lib = json.loads(src)
# (re-runnable: the old floors 4 and 5 are read from git's HEAD copy when they've already been rebuilt)
if any(r['id'] == 4 and r.get('missionHeading') == 'Recording A' for r in lib):
    import subprocess
    head = {r['id']: r for r in json.loads(subprocess.check_output(['git', 'show', 'HEAD:' + PATH]))}
    lib = [head[r['id']] if r['id'] in STUDIOS else r for r in lib]
assert dump(json.loads(src)) == src, 'unexpected file format -- not rewriting'
out = [build(r, r['id']) if r['id'] in STUDIOS else r for r in lib]
open(PATH, 'w').write(dump(out))
for f in STUDIOS:
    r = next(x for x in out if x['id'] == f)
    print('floor', f, 'cells', len(r['cells']), 'doors', [(d['label'], d['coord'], d['direction']) for d in r['roomEntranceDoors']])
